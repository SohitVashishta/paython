#Take two numbers as input from the user and print their sum and difference.
num1=input("Enter the first number: ")
num2=input("Enter the second number: ")

function_sum=int(num1)+int(num2)
function_diff=int(num1)-int(num2)
function_multiply=int(num1)*int(num2)
function_divide=int(num1)/int(num2)

print("Addition of the two numbers is:",function_sum)
print("Subtraction of the two numbers is:",function_diff)
print("Multiplication of the two numbers is:",function_multiply)
print("Division of the two numbers is:",function_divide)

